#!/usr/bin/env bash
# Install the closing-line saver as a launchd job.
#
#     bash tools/install_lines_job.sh
#
# Every 20 minutes runs tools/line_snapshot.py --closing 45: Sportsbet's
# player lines for any game tipping in the next 45 minutes, saved under
# journal/lines/ (gitignored). The last one before each tip is that
# game's closing line, which the Journal compares with the lines on your
# slips. Outside game windows each run is one request and exits. The Mac
# has to be awake for it -- caffeinate on game days.
#
# Same safeguards as tools/install_refresh_job.sh: refuses a checkout in
# a macOS-protected folder (launchd's bash cannot read ~/Documents,
# ~/Desktop or ~/Downloads and fails silently), and writes the python on
# YOUR PATH into the job, because launchd's bare PATH finds a python3
# with no pandas.

set -uo pipefail

LABEL="com.boxscorewhisperer.lines"
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"

say() { printf '  %s\n' "$*"; }
die() { printf '\nSTOPPED: %s\n' "$*" >&2; exit 1; }

echo
say "repo:  $REPO_DIR"
say "plist: $PLIST"
echo

case "$REPO_DIR/" in
    "$HOME/Documents/"*|"$HOME/Desktop/"*|"$HOME/Downloads/"*)
        die "this checkout is inside a folder macOS protects; launchd could not read it.
  Move it to ~/Projects first (see tools/install_refresh_job.sh)."
        ;;
esac
[ -f "$REPO_DIR/tools/line_snapshot.py" ] || die "tools/line_snapshot.py is missing"

PYTHON_BIN="$(command -v python3 2>/dev/null || true)"
[ -n "$PYTHON_BIN" ] || die "no python3 on PATH"
PYTHON_DIR="$(cd "$(dirname "$PYTHON_BIN")" && pwd -P)"
PYTHON_BIN="$PYTHON_DIR/$(basename "$PYTHON_BIN")"
for mod in pandas nba_api requests; do
    "$PYTHON_BIN" -c "import $mod" >/dev/null 2>&1 || die "$PYTHON_BIN cannot import $mod"
done
say "python: $PYTHON_BIN"

mkdir -p "$HOME/Library/LaunchAgents" "$REPO_DIR/logs" || die "could not create directories"

cat > "$PLIST" <<PLISTEOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/install_lines_job.sh -- do not hand-edit. -->
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$LABEL</string>
    <key>ProgramArguments</key>
    <array>
        <string>$PYTHON_BIN</string>
        <string>-u</string>
        <string>$REPO_DIR/tools/line_snapshot.py</string>
        <string>--closing</string>
        <string>45</string>
    </array>
    <key>WorkingDirectory</key>
    <string>$REPO_DIR</string>
    <key>EnvironmentVariables</key>
    <dict>
        <key>PYTHON</key>
        <string>$PYTHON_BIN</string>
        <key>PATH</key>
        <string>$PYTHON_DIR:/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
    </dict>
    <key>StartInterval</key>
    <integer>1200</integer>
    <key>RunAtLoad</key>
    <false/>
    <key>StandardOutPath</key>
    <string>$REPO_DIR/logs/lines_job.log</string>
    <key>StandardErrorPath</key>
    <string>$REPO_DIR/logs/lines_job.log</string>
</dict>
</plist>
PLISTEOF
say "wrote the plist"

launchctl unload "$PLIST" >/dev/null 2>&1
launchctl load "$PLIST" 2>/dev/null || die "launchctl load failed"
STATUS="$(launchctl list | grep "$LABEL" || true)"
[ -n "$STATUS" ] || die "the job did not load"
say "loaded: $STATUS"
echo
say "Runs every 20 minutes. Each run prints the files it saved to:"
say "    $REPO_DIR/logs/lines_job.log"
say "To save every listed game's lines right now:"
say "    $PYTHON_BIN tools/line_snapshot.py"
echo
