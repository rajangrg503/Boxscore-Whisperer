#!/usr/bin/env bash
# Install the twice-daily game-log refresh as a launchd job.
#
#     bash tools/install_logs_job.sh
#
# Runs tools/refresh_logs.sh at 17:45 and 07:15 every day: after the US
# slate is final in Sydney, and a catch-up before the next one tips. If
# the Mac is asleep at a run time, launchd runs it once on waking.
#
# Same safeguards as tools/install_refresh_job.sh: refuses a checkout in
# a macOS-protected folder (launchd's bash cannot read ~/Documents,
# ~/Desktop or ~/Downloads and fails silently), and writes the python on
# YOUR PATH into the job, because launchd's bare PATH finds a python3
# with no pandas.

set -uo pipefail

LABEL="com.boxscorewhisperer.logs"
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"

say() { printf '  %s\n' "$*"; }
die() { printf '\nSTOPPED: %s\n' "$*" >&2; exit 1; }

echo
say "repo:  $REPO_DIR"
say "plist: $PLIST"
echo

case "$REPO_DIR/" in
    "$HOME/Documents/"*|"$HOME/Desktop/"*|"$HOME/Downloads/"*)
        die "this checkout is inside a folder macOS protects; launchd could not read it.
  Move it to ~/Projects first (see tools/install_refresh_job.sh)."
        ;;
esac
[ -f "$REPO_DIR/tools/refresh_logs.sh" ] || die "tools/refresh_logs.sh is missing"

PYTHON_BIN="$(command -v python3 2>/dev/null || true)"
[ -n "$PYTHON_BIN" ] || die "no python3 on PATH"
PYTHON_DIR="$(cd "$(dirname "$PYTHON_BIN")" && pwd -P)"
PYTHON_BIN="$PYTHON_DIR/$(basename "$PYTHON_BIN")"
for mod in pandas nba_api requests; do
    "$PYTHON_BIN" -c "import $mod" >/dev/null 2>&1 || die "$PYTHON_BIN cannot import $mod"
done
say "python: $PYTHON_BIN"

mkdir -p "$HOME/Library/LaunchAgents" "$REPO_DIR/logs" || die "could not create directories"

cat > "$PLIST" <<PLISTEOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/install_logs_job.sh -- do not hand-edit. -->
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$LABEL</string>
    <key>ProgramArguments</key>
    <array>
        <string>/bin/bash</string>
        <string>$REPO_DIR/tools/refresh_logs.sh</string>
    </array>
    <key>WorkingDirectory</key>
    <string>$REPO_DIR</string>
    <key>EnvironmentVariables</key>
    <dict>
        <key>PYTHON</key>
        <string>$PYTHON_BIN</string>
        <key>PATH</key>
        <string>$PYTHON_DIR:/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
    </dict>
    <key>StartCalendarInterval</key>
    <array>
        <dict><key>Hour</key><integer>17</integer><key>Minute</key><integer>45</integer></dict>
        <dict><key>Hour</key><integer>7</integer><key>Minute</key><integer>15</integer></dict>
    </array>
    <key>RunAtLoad</key>
    <false/>
    <key>StandardOutPath</key>
    <string>$REPO_DIR/logs/logs_job.out</string>
    <key>StandardErrorPath</key>
    <string>$REPO_DIR/logs/logs_job.err</string>
</dict>
</plist>
PLISTEOF
say "wrote the plist"

launchctl unload "$PLIST" >/dev/null 2>&1
launchctl load "$PLIST" 2>/dev/null || die "launchctl load failed"
STATUS="$(launchctl list | grep "$LABEL" || true)"
[ -n "$STATUS" ] || die "the job did not load"
say "loaded: $STATUS"
echo
say "Runs at 17:45 and 07:15 daily. To run it now and watch:"
say "    launchctl kickstart -k gui/\$UID/$LABEL"
say "    tail -f $REPO_DIR/logs/logs_refresh.log"
echo
